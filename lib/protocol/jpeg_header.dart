import 'dart:typed_data';

/// Builds the JPEG header that BL608-family cameras leave out of the stream.
///
/// The camera sends only entropy-coded scan data plus a quality value, width
/// and height. Everything else is baseline JPEG with the example tables from
/// ITU T.81 Annex K, so the header can be generated rather than stored.
class JpegHeader {
  JpegHeader._();

  static const supportedQualities = {5, 10, 25, 50, 75, 100};

  /// Returns the header, or null if [quality] isn't one the camera can use.
  static Uint8List? build({
    required int quality,
    required int width,
    required int height,
  }) {
    if (!supportedQualities.contains(quality)) return null;
    final b = BytesBuilder(copy: false);
    b.add(const [0xFF, 0xD8]);
    _dqt(b, 0, _lumaQuant, quality);
    _dqt(b, 1, _chromaQuant, quality);
    // Start of frame: 8-bit, three components, no chroma subsampling.
    b.add([
      0xFF, 0xC0, 0x00, 0x11, 0x08,
      (height >> 8) & 0xFF, height & 0xFF,
      (width >> 8) & 0xFF, width & 0xFF,
      0x03, 0x01, 0x11, 0x00, 0x02, 0x11, 0x01, 0x03, 0x11, 0x01,
    ]);
    _dht(b, 0x00, _dcLumaBits, _dcValues);
    _dht(b, 0x10, _acLumaBits, _acLumaValues);
    _dht(b, 0x01, _dcChromaBits, _dcValues);
    _dht(b, 0x11, _acChromaBits, _acChromaValues);
    // Start of scan: the camera's entropy-coded data follows directly.
    b.add(const [
      0xFF, 0xDA, 0x00, 0x0C, 0x03,
      0x01, 0x00, 0x02, 0x11, 0x03, 0x11,
      0x00, 0x3F, 0x00,
    ]);
    return b.toBytes();
  }

  static void _dqt(BytesBuilder b, int id, List<int> base, int quality) {
    final scale = quality < 50 ? 5000 ~/ quality : 200 - quality * 2;
    b.add([0xFF, 0xDB, 0x00, 0x43, id]);
    for (final natural in _zigzag) {
      b.addByte(((base[natural] * scale + 50) ~/ 100).clamp(1, 255));
    }
  }

  static void _dht(BytesBuilder b, int tc, List<int> bits, List<int> values) {
    final length = 3 + bits.length + values.length;
    b.add([0xFF, 0xC4, (length >> 8) & 0xFF, length & 0xFF, tc]);
    b.add(bits);
    b.add(values);
  }

  static const _zigzag = [
    0, 1, 8, 16, 9, 2, 3, 10, 17, 24, 32, 25, 18, 11, 4, 5,
    12, 19, 26, 33, 40, 48, 41, 34, 27, 20, 13, 6, 7, 14, 21, 28,
    35, 42, 49, 56, 57, 50, 43, 36, 29, 22, 15, 23, 30, 37, 44, 51,
    58, 59, 52, 45, 38, 31, 39, 46, 53, 60, 61, 54, 47, 55, 62, 63,
  ];

  // T.81 Table K.1
  static const _lumaQuant = [
